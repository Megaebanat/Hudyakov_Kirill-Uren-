import 'package:flutter/services.dart' show rootBundle;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../common/logging/app_logger.dart';

/// Сервис подготовки документов: генерация PDF Политики конфиденциальности
/// и Пользовательского соглашения (модуль Г, спринт 3).
///
/// Документы формируются офлайн из встроенного шрифта Inter — без обращений
/// к сети, что соответствует ограничениям площадки чемпионата.
///
/// Ответственность (SRP): только подготовка PDF-документов.
///
/// Дата создания: 19-10-2026
/// Автор: Участник №00
class DocumentService {
  /// Шрифт с кириллицей (тот же, что в макете — assets/fonts/Inter.ttf).
  Future<pw.Font> _loadFont() async {
    final data = await rootBundle.load('assets/fonts/Inter.ttf');
    return pw.Font.ttf(data);
  }

  /// Собирает PDF Политики конфиденциальности.
  ///
  /// Без параметров; возвращает байты готового PDF-файла.
  Future<List<int>> buildPrivacyPolicyPdf() async {
    AppLogger.info(
      'DocumentService',
      'Генерация PDF',
      'Политика конфиденциальности',
    );
    return _build(
      title: 'Политика конфиденциальности',
      sections: const [
        (
          '1. Общие положения',
          'Настоящая Политика описывает, как обрабатываются персональные '
              'данные пользователей приложения: адрес электронной почты, имя, '
              'фотография профиля, результаты игр и статистика. Используя '
              'приложение, пользователь подтверждает согласие на обработку '
              'данных в объёме, необходимом для работы сервиса.',
        ),
        (
          '2. Какие данные собираются',
          '— электронная почта и имя учётной записи;\n'
              '— фотография профиля (по желанию пользователя);\n'
              '— данные о созданных и сыгранных играх, результаты, очки;\n'
              '— технические данные для отладки работы приложения.',
        ),
        (
          '3. Цели обработки',
          'Данные используются для аутентификации, отображения статистики, '
              'организации игр между пользователями и направления локальных '
              'напоминаний о предстоящих матчах.',
        ),
        (
          '4. Хранение и защита',
          'Данные передаются по защищённому протоколу HTTPS и хранятся на '
              'серверах оператора сервиса. Доступ к данным имеют только '
              'системные компоненты, необходимые для работы приложения.',
        ),
        (
          '5. Права пользователя',
          'Пользователь вправе запросить удаление учётной записи и всех '
              'связанных данных, обратившись в службу поддержки приложения.',
        ),
      ],
    );
  }

  /// Собирает PDF Пользовательского соглашения.
  ///
  /// Без параметров; возвращает байты готового PDF-файла.
  Future<List<int>> buildUserAgreementPdf() async {
    AppLogger.info(
      'DocumentService',
      'Генерация PDF',
      'Пользовательское соглашение',
    );
    return _build(
      title: 'Пользовательское соглашение',
      sections: const [
        (
          '1. Предмет соглашения',
          'Соглашение регулирует отношения между пользователем и оператором '
              'приложения по использованию функций планирования и проведения '
              'игр, ведения профиля и статистики.',
        ),
        (
          '2. Учётная запись',
          'Пользователь обязан указывать достоверные данные при регистрации '
              'и обеспечивать конфиденциальность своего пароля. Действия, '
              'выполненные из учётной записи, считаются совершёнными '
              'пользователем.',
        ),
        (
          '3. Правила проведения игр',
          'Игра завершается автоматически после сборки головоломки; '
              'побеждает игрок, завершивший её быстрее. Закрытие игры до '
              'завершения считается поражением. Результаты сохраняются '
              'на сервере для формирования статистики.',
        ),
        (
          '4. Ограничение ответственности',
          'Оператор не несёт ответственности за перерывы в работе серверов, '
              'вызванные техническим обслуживанием или форс-мажором.',
        ),
      ],
    );
  }

  /// Формирует PDF-документ из заголовка и разделов.
  ///
  /// [title] — заголовок документа; [sections] — пары «заголовок, текст».
  Future<List<int>> _build({
    required String title,
    required List<(String, String)> sections,
  }) async {
    final font = await _loadFont();
    final document = pw.Document();
    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        theme: pw.ThemeData.withFont(base: font, bold: font),
        header: (context) => pw.Text(
          title,
          style: pw.TextStyle(
            font: font,
            fontSize: 18,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
        footer: (context) => pw.Align(
          alignment: pw.Alignment.centerRight,
          child: pw.Text(
            'Стр. ${context.pageNumber} из ${context.pagesCount}',
            style: pw.TextStyle(font: font, fontSize: 9),
          ),
        ),
        build: (context) => [
          for (final (heading, body) in sections) ...[
            pw.SizedBox(height: 14),
            pw.Text(
              heading,
              style: pw.TextStyle(
                font: font,
                fontSize: 13,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.SizedBox(height: 6),
            pw.Text(
              body,
              style: pw.TextStyle(font: font, fontSize: 11, lineSpacing: 4),
            ),
          ],
        ],
      ),
    );
    return document.save();
  }
}
