import 'http_request.dart';

/// Транспортный уровень: отправка HTTP-запросов на физическое носителя сети.
///
/// Ответственность (SRP): единственная обязанность — «как отправить байты».
/// Благодаря этому интерфейсу библиотеку транспорта (dart:io, Dio, Cronet)
/// можно заменить, не меняя код выше по стеку (DIP).
///
/// Дата создания: 19-10-2026
/// Автор: Участник №00
abstract interface class HttpTransport {
  /// Отправляет [request] и возвращает сырой HTTP-ответ.
  ///
  /// Бросает [TransportException] при недоступности сети или истечении таймаута.
  Future<HttpResponse> send(HttpRequest request);
}
